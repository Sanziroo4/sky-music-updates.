import test from 'node:test';
import assert from 'node:assert/strict';
import {BASE,OUTPUT,INPUT,hex,decode,encode,examples,run,createMachine,step} from '../engine.mjs';
test('ADD fields, result and sequential PC',()=>{const d=decode(0x01095020);assert.deepEqual(d.fields.map(f=>f.bits),['000000','01000','01001','01010','00000','100000']);const s=run(examples.add);assert.equal(s.regs[10],12);assert.equal(s.pc,BASE+4);assert.equal(s.error,null);});
test('negative immediate sign extension',()=>assert.equal(run(examples.negative).regs[10],4));
test('ADD and ADDI overflow prevent write and stop',()=>{for(const name of ['add','addi']){const s=run({words:[encode({name,rs:8,rt:9,rd:10,imm:1})],regs:{8:2147483647,9:1}});assert.match(s.error,/overflow/);assert.equal(s.regs[name==='add'?10:9],name==='add'?0:1);assert.equal(s.pc,BASE);}});
test('ADDU wraps and zero remains immutable',()=>{let s=run({words:[encode({name:'addu'})],regs:{8:0xffffffff,9:1}});assert.equal(s.regs[10],0);s=run({words:[encode({name:'add',rd:0})],regs:{8:7,9:5,0:9}});assert.equal(s.regs[0],0);});
test('bitwise and signed slt',()=>{for(const [name,a,b,want] of [['and',12,10,8],['or',12,10,14],['slt',0xffffffff,1,1],['slt',3,1,0]])assert.equal(run({words:[encode({name})],regs:{8:a,9:b}}).regs[10],want);});
test('load/store and negative offset',()=>{const s=run(examples.memory);assert.equal(s.error,null);assert.equal(s.regs[8],7);assert.equal(s.mem[0x10010004],12);const n=run({words:[encode({name:'lw',rs:16,rt:8,imm:-4})],regs:{16:0x10010004},mem:{[0x10010000]:33}});assert.equal(n.regs[8],33);});
test('unaligned reads and writes fail without writing',()=>{for(const name of ['lw','sw']){const s=run({words:[encode({name,rs:16,rt:8,imm:2})],regs:{16:0x10010000,8:7}});assert.match(s.error,/тураланбаған/);assert.equal(s.mem[0x10010002],undefined);}});
test('branch target after one complete nop delay slot',()=>{const s=run(examples.branch);assert.deepEqual(s.trace,[BASE,BASE+4,BASE+12]);assert.equal(s.regs[10],0);assert.equal(s.regs[11],2);assert.equal(s.steps,10);});
test('jump target, delay slot and PC upper nibble',()=>{const s=run(examples.jump);assert.deepEqual(s.trace,[BASE,BASE+4,BASE+12]);assert.equal(s.regs[11],2);const m=createMachine({words:[0x08000003,0]});m.pc=0x10400000;m.program={0x10400000:0x08000003,0x10400004:0};m.end=0x10400008;let a=step(step(step(m)));assert.equal(a.pending,0x1000000c);});
test('lock code 42 and 17 use different paths and both execute nop',()=>{for(const [n,want,trace]of [[42,1,[0,4,8,12,16]],[17,0,[0,4,8,16]]]){const s=run(examples.lock,n);assert.equal(s.error,null);assert.equal(s.mem[OUTPUT],want);assert.deepEqual(s.trace,trace.map(x=>BASE+x));assert.equal(s.regs[8],n);}});
test('write to keyboard is rejected',()=>{const s=run({words:[0xae080000],regs:{16:INPUT,8:7}},42);assert.match(s.error,/тек оқуға/);assert.equal(s.mem[INPUT],42);});
test('pure transitions preserve prior state including memory, pending and trace',()=>{let s=createMachine(examples.lock,42);const snapshots=[];for(let i=0;i<15;i++){snapshots.push(structuredClone(s));const old=structuredClone(s);s=step(s);assert.deepEqual(snapshots.at(-1),old);}assert.equal(s.mem[OUTPUT],1);assert.equal(snapshots[14].mem[OUTPUT],0);assert.equal(snapshots[6].pending,BASE+12);});
test('invalid opcode, reserved shamt and range rejection',()=>{assert.throws(()=>decode(0xffffffff),/Қолдау/);assert.throws(()=>decode(0x01095060),/shamt/);assert.throws(()=>encode({name:'addi',imm:32768}),/Immediate/);assert.throws(()=>encode({name:'j',target:3}),/тураланған/);});
test('invalid fetch and backward branch signed offset',()=>{const s=run({words:[encode({name:'beq',rs:0,rt:0,imm:20}),0]});assert.match(s.error,/жарамсыз/);const loop=run({words:[encode({name:'beq',rs:0,rt:0,imm:-1}),0]},42,30);assert.equal(loop.steps,30);assert.equal(loop.error,null);assert.deepEqual(loop.trace.slice(0,4),[BASE,BASE+4,BASE,BASE+4]);});
test('all supported instruction encodings round-trip',()=>{for(const name of ['add','addu','addi','and','or','slt','lw','sw','beq','bne','j','nop'])assert.equal(decode(encode({name})).name,name);});
test('ADDI overflow exposes the actual ALU inputs and untruncated result at Execute',()=>{
 let s=createMachine(examples.overflow);
 s=step(s);s=step(s);
 const decodeSnapshot=structuredClone(s);
 s=step(s);
 assert.equal(s.stage,2);
 assert.equal(s.halted,true);
 assert.equal(s.effect.a,2147483647);
 assert.equal(s.effect.immediate,1);
 assert.equal(s.effect.right,1);
 assert.equal(s.effect.rawResult,2147483648);
 assert.equal(s.effect.dest,10);
 assert.equal(s.effect.result,undefined);
 assert.equal(s.effect.overflow,true);
 assert.equal(s.effect.writeBlocked,true);
 assert.equal(s.changed,null);
 assert.equal(s.pc,BASE);
 assert.equal(s.regs[10],0);
 assert.deepEqual(s.mem,decodeSnapshot.mem);
 assert.deepEqual(s.program,decodeSnapshot.program);
 assert.equal(decodeSnapshot.stage,1);
 assert.equal(decodeSnapshot.effect,null);
 assert.match(s.log.at(-1),/^EXECUTE ҚАТЕ · addi \$t2, \$t0, 1 · 2147483647 \+ 1 = 2147483648/);
 assert.deepEqual(step(s),s);
 // Replaying from the prior snapshot and restarting produce the same state.
 assert.deepEqual(step(decodeSnapshot),s);
 assert.equal(createMachine(examples.overflow).regs[10],0);
});
test('ADD overflow preserves a nonzero destination; negative overflow retains its signed calculation',()=>{
 const add=run({words:[encode({name:'add',rs:8,rt:9,rd:10})],regs:{8:2147483647,9:1,10:123}});
 assert.equal(add.stage,2);
 assert.equal(add.regs[10],123);
 assert.equal(add.effect.right,1);
 assert.equal(add.effect.rawResult,2147483648);
 assert.equal(add.effect.immediate,undefined);
 assert.match(add.log.at(-1),/^EXECUTE ҚАТЕ/);
 const negative=run({words:[encode({name:'addi',rs:8,rt:10,imm:-1})],regs:{8:0x80000000,10:99}});
 assert.equal(negative.effect.right,-1);
 assert.equal(negative.effect.rawResult,-2147483649);
 assert.equal(negative.regs[10],99);
 assert.equal(negative.pc,BASE);
 assert.match(negative.log.at(-1),/-2147483648 \+ -1 = -2147483649/);
});
test('valid signed ADDI boundary writes normally without an overflow flag',()=>{
 const s=run({words:[encode({name:'addi',rs:8,rt:10,imm:1})],regs:{8:2147483646}});
 assert.equal(s.error,null);
 assert.equal(s.regs[10],2147483647);
 assert.equal(s.effect.rawResult,2147483647);
 assert.equal(s.effect.overflow,undefined);
 assert.equal(s.pc,BASE+4);
});
